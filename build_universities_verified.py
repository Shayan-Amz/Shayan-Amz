def new_sheet(name, widths, title, subtitle, rtl=True):
    ws = wb.create_sheet(name)
    if rtl:
        ws.sheet_view.rightToLeft = True
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    n = len(widths)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=n)
    c = ws.cell(row=1, column=1, value=title)
    c.font = f_title
    c.alignment = Alignment(horizontal="right", vertical="center")
    ws.row_dimensions[1].height = 30
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=n)
    c = ws.cell(row=2, column=1, value=subtitle)
    c.font = f_sub
    c.alignment = Alignment(horizontal="right", vertical="top", wrap_text=True)
    ws.row_dimensions[2].height = 42
    return ws


def header_row(ws, row, headers):
    for j, h in enumerate(headers, start=1):
        c = ws.cell(row=row, column=j, value=h)
        c.font = f_head
        c.fill = fill_head
        c.alignment = a_rtl_c
        c.border = border
    ws.row_dimensions[row].height = 34


def body_rows(ws, start, rows, heights=None, fill_fn=None, bold_cols=()):
    for i, row in enumerate(rows):
        r = start + i
        for j, v in enumerate(row, start=1):
            c = ws.cell(row=r, column=j, value=v)
            if isinstance(v, str) and v.startswith("="):
                # رتبهٔ مشترک QS مثل «=228» متن است نه فرمول؛ بدون این خط openpyxl آن را فرمولِ نامعتبر می‌نویسد
                # و اکسل هنگام باز کردن پیام «ترمیم فایل» می‌دهد.
                c.data_type = "s"
            c.font = f_body_b if j in bold_cols else f_body
            c.alignment = a_rtl
            c.border = border
            if fill_fn:
                fl = fill_fn(j, v)
                if fl:
                    c.fill = fl
            elif i % 2 == 1:
                c.fill = fill_alt
        if heights:
            ws.row_dimensions[r].height = heights[i] if i < len(heights) else heights[-1]
    return start + len(rows)


def verdict_of(v):
    """رنگ حکم بر اساس وجود اموجی در متن (اولویت: قرمز > زرد > سبز)."""
    s = str(v).strip()
    if s.startswith("⚠"):  # حکم مشروط که صریحاً با ⚠️ شروع شده → زرد
        return fill_warn
    if "❌" in s:
        return fill_bad
    if "⚠" in s:
        return fill_warn
    if "✅" in s:
        return fill_ok
    return None


